/**
 * Helper to safely retrieve dealership inventory data by ID
 */
export function getDealershipInventory(id) {
  if (!id) return DEALERSHIP_INVENTORIES['shop_hyundai_1'];
  
  // Direct match
  if (DEALERSHIP_INVENTORIES[id]) {
    return DEALERSHIP_INVENTORIES[id];
  }

  // Token matching
  if (id.includes('moto') || id.includes('bike')) {
    return DEALERSHIP_INVENTORIES['shop_moto_world'];
  }
  if (id.includes('maruti')) {
    return DEALERSHIP_INVENTORIES['shop_maruti_car_point'];
  }
  if (id.includes('honda')) {
    return DEALERSHIP_INVENTORIES['shop_honda_2_wheelers'];
  }
  if (id.includes('commercial') || id.includes('truck')) {
    return DEALERSHIP_INVENTORIES['shop_kerala_commercial'];
  }

  // Default fallback to Hyundai Auto Hub
  return DEALERSHIP_INVENTORIES['shop_hyundai_1'];
}
